"""Merge per-worker workaround parts into one reviewable Markdown log."""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

PARTS_DIR = "workarounds"
OUTPUT = "RESEARCH_WORKAROUNDS.md"
PLAYBOOK = "RESEARCH_PLAYBOOK.md"
OTHER = "Other"
NON_CHANNEL_SECTIONS = {"mandate", "off-limits", "when a workaround works", "every channel"}
HEADING = re.compile(r"^###\s+(?P<date>\d{4}-\d{2}-\d{2})\s*·\s*(?P<channel>[^·]+?)\s*·\s*(?P<title>.+?)\s*$")


@dataclass
class Entry:
    date: str
    channel: str
    title: str
    body: str
    part: str


def playbook_channels(root: Path) -> list[str]:
    """Channel names are the playbook's level-two headings after the general sections."""
    path = root / PLAYBOOK
    if not path.is_file():
        return []
    names = re.findall(r"^## (.+?)\s*$", path.read_text(encoding="utf-8"), re.MULTILINE)
    return [name for name in names if name.lower() not in NON_CHANNEL_SECTIONS]


def parse_part(path: Path, root: Path, channels: list[str]) -> tuple[list[Entry], list[str]]:
    lookup = {name.lower(): name for name in channels}
    entries: list[Entry] = []
    problems: list[str] = []
    relative = path.relative_to(root).as_posix()
    current: dict | None = None
    lines: list[str] = []

    def flush() -> None:
        if current is not None:
            entries.append(Entry(body="\n".join(lines).strip(), part=relative, **current))

    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if line.startswith("### "):
            flush()
            lines = []
            match = HEADING.match(line)
            if match:
                channel = lookup.get(match["channel"].strip().lower())
                if channel is None:
                    problems.append(f"{relative}:{number}: unknown channel {match['channel'].strip()!r}, filed under {OTHER}")
                    channel = OTHER
                current = {"date": match["date"], "channel": channel, "title": match["title"]}
            else:
                problems.append(f"{relative}:{number}: heading is not '### YYYY-MM-DD · channel · title', filed under {OTHER}")
                current = {"date": "0000-00-00", "channel": OTHER, "title": line[4:].strip()}
        elif current is not None:
            lines.append(line)
    flush()
    return entries, problems


def collect(root: Path) -> tuple[list[Entry], list[str], int]:
    channels = playbook_channels(root)
    parts = sorted((root / PARTS_DIR).glob("*.md")) if (root / PARTS_DIR).is_dir() else []
    entries: list[Entry] = []
    problems: list[str] = []
    for part in parts:
        found, issues = parse_part(part, root, channels)
        entries.extend(found)
        problems.extend(issues)
    return entries, problems, len(parts)


def render(root: Path, entries: list[Entry], part_count: int) -> str:
    order = playbook_channels(root) + [OTHER]
    out = [
        "# Research workarounds",
        "",
        f"Generated by `tools/merge_workarounds.py` from `{PARTS_DIR}/*.md`. Do not edit this file by hand.",
        f"Review the entries, then promote the ones worth keeping into `{PLAYBOOK}`.",
        "",
        f"{len(entries)} entries from {part_count} parts.",
        "",
    ]
    if not entries:
        out += ["No workarounds recorded yet.", ""]
    for channel in order:
        group = sorted((e for e in entries if e.channel == channel), key=lambda e: (e.date, e.part, e.title))
        if not group:
            continue
        out += [f"## {channel}", ""]
        for entry in group:
            out += [f"### {entry.date} · {entry.title}", "", f"_From `{entry.part}`_", ""]
            if entry.body:
                out += [entry.body, ""]
    return "\n".join(out).rstrip() + "\n"


def merge(root: Path) -> tuple[Path, int, list[str]]:
    entries, problems, part_count = collect(root)
    path = root / OUTPUT
    temporary = path.with_suffix(".md.tmp")
    temporary.write_text(render(root, entries, part_count), encoding="utf-8")
    temporary.replace(path)
    return path, len(entries), problems
